#!/usr/bin/env python3
# Generate the committed USDT probe header (src/node_provider_linux.h)
# from src/node_provider.d using the SystemTap `dtrace` wrapper.
#
# The header is committed to the repository so that Node.js can be built
# with USDT probe support on Linux without a `dtrace` tool at build time;
# only <sys/sdt.h> is required (from the systemtap-sdt-dev package on
# Debian/Ubuntu, or systemtap-sdt-devel on Fedora/RHEL).
#
# Usage:
#   python3 tools/usdt/generate_headers.py           # regenerate
#   python3 tools/usdt/generate_headers.py --check    # verify (CI)
#
# The SystemTap `dtrace` wrapper must be in PATH. Override the binary
# with --dtrace or the DTRACE environment variable. The native DTrace
# implementations (macOS, FreeBSD, illumos) are deliberately rejected:
# they produce a different, platform-specific header and require extra
# link-time processing; only the SystemTap output is committed.

import argparse
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PROVIDER = os.path.join(ROOT, 'src', 'node_provider.d')
OUTPUT = os.path.join(ROOT, 'src', 'node_provider_linux.h')

BANNER = """\
/*
 * This file is generated by tools/usdt/generate_headers.py from
 * src/node_provider.d using the SystemTap `dtrace` wrapper. Do not
 * edit it by hand.
 *
 * Regenerate with: python3 tools/usdt/generate_headers.py
 * The test-usdt CI job verifies that this file is in sync with
 * src/node_provider.d.
 */

"""


def generate(dtrace_bin):
    fd, tmp = tempfile.mkstemp(suffix='.h')
    os.close(fd)
    try:
        subprocess.check_call(
            [dtrace_bin, '-h', '-s', PROVIDER, '-o', tmp], cwd=ROOT)
        with open(tmp) as f:
            content = f.read()
    finally:
        os.unlink(tmp)

    if 'Systemtap dtrace wrapper' not in content:
        sys.exit(
            '%s did not produce SystemTap output. The header must be '
            'generated with the SystemTap dtrace wrapper '
            '(systemtap-sdt-dev on Debian/Ubuntu, systemtap-sdt-devel on '
            'Fedora/RHEL), not a native DTrace implementation.' % dtrace_bin)

    return BANNER + content


def main():
    parser = argparse.ArgumentParser(
        description='Regenerate committed USDT probe headers.')
    parser.add_argument(
        '--check', action='store_true',
        help='verify that the committed header is up to date; '
             'exit with 1 on drift')
    parser.add_argument(
        '--dtrace', default=os.environ.get('DTRACE', 'dtrace'),
        help='path to the SystemTap dtrace wrapper [default: %(default)s]')
    args = parser.parse_args()

    content = generate(args.dtrace)

    if args.check:
        with open(OUTPUT) as f:
            committed = f.read()
        if committed != content:
            sys.exit(
                '%s is out of date with src/node_provider.d. '
                'Regenerate it with: python3 tools/usdt/generate_headers.py'
                % OUTPUT)
        print('%s is up to date' % OUTPUT)
        return

    with open(OUTPUT, 'w') as f:
        f.write(content)
    print('wrote %s' % OUTPUT)


if __name__ == '__main__':
    main()
