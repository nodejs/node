'use strict';
const common = require('../common');
const assert = require('assert');
const { WASI } = require('wasi');

// deps/uvwasi/include/wasi_types.h
const UVWASI_ESUCCESS = 0;
const UVWASI_EOVERFLOW = 61;

// _start calls fd_read and stores each errno:
//   0: iovs_len 0x20000000 (0x20000000 * 8 wraps uint32_t to 0)
//   4: iovs_len 0x20000001 (wraps to 8, which fits in one page)
//   8: iovs_len 0
const bytes = Uint8Array.from([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, 0x01, 0x0c, 0x02, 0x60, 0x00, 0x00, 0x60, 0x04,
  0x7f, 0x7f, 0x7f, 0x7f, 0x01, 0x7f, 0x02, 0x22, 0x01, 0x16, 0x77, 0x61, 0x73, 0x69, 0x5f, 0x73,
  0x6e, 0x61, 0x70, 0x73, 0x68, 0x6f, 0x74, 0x5f, 0x70, 0x72, 0x65, 0x76, 0x69, 0x65, 0x77, 0x31,
  0x07, 0x66, 0x64, 0x5f, 0x72, 0x65, 0x61, 0x64, 0x00, 0x01, 0x03, 0x02, 0x01, 0x00, 0x05, 0x03,
  0x01, 0x00, 0x01, 0x07, 0x13, 0x02, 0x06, 0x6d, 0x65, 0x6d, 0x6f, 0x72, 0x79, 0x02, 0x00, 0x06,
  0x5f, 0x73, 0x74, 0x61, 0x72, 0x74, 0x00, 0x01, 0x0a, 0x39, 0x01, 0x37, 0x00, 0x41, 0x00, 0x41,
  0x00, 0x41, 0x00, 0x41, 0x80, 0x80, 0x80, 0x80, 0x02, 0x41, 0x10, 0x10, 0x00, 0x36, 0x02, 0x00,
  0x41, 0x04, 0x41, 0x00, 0x41, 0x00, 0x41, 0x81, 0x80, 0x80, 0x80, 0x02, 0x41, 0x10, 0x10, 0x00,
  0x36, 0x02, 0x00, 0x41, 0x08, 0x41, 0x00, 0x41, 0x00, 0x41, 0x00, 0x41, 0x10, 0x10, 0x00, 0x36,
  0x02, 0x00, 0x0b,
]);

(async () => {
  const wasi = new WASI({ version: 'preview1', returnOnExit: true });
  const { instance } = await WebAssembly.instantiate(bytes, wasi.getImportObject());
  assert.strictEqual(wasi.start(instance), 0);

  const view = new DataView(instance.exports.memory.buffer);
  assert.strictEqual(view.getUint32(0, true), UVWASI_EOVERFLOW);
  assert.strictEqual(view.getUint32(4, true), UVWASI_EOVERFLOW);
  assert.strictEqual(view.getUint32(8, true), UVWASI_ESUCCESS);
})().then(common.mustCall());
